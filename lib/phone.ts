/**
 * 연락처.
 *
 * 🔑 검증을 느슨하게 잡은 이유
 *   이 값의 쓸모는 **"주문에 문제가 생겼을 때 연락이 닿는 것"** 하나다.
 *   그런데 형식을 촘촘히 잡을수록 진짜 번호가 거절당한다 — 070·안심번호·지역번호·
 *   해외 체류 중인 부모의 번호까지. 거절당한 사람은 형식을 맞추려고 **가짜를 넣는다.**
 *   그러면 검증이 통과한 대신 연락은 안 닿는다. 검증이 목적을 배신하는 경우다.
 *
 * 🔴 그런데 코드가 그 주석과 반대로 동작하고 있었다.
 *   상한이 11자리라 **주석이 예로 든 번호들이 정확히 차단됐다** —
 *   안심번호 `0503-1234-5678`(12자리), 국가번호를 붙인 `+82 10-1234-5678`(12자리).
 *   안심번호는 커머스에서 아주 흔하다.
 *
 *   더 나쁜 건 저장 쪽이었다. 모르는 자릿수를 **한국 휴대폰 규칙으로 임의 재조립**해서
 *   사용자가 넣지 않은 모양으로 저장했다. 연락이 닿는 게 목적인 값을 **바꿔서 저장한 것이다.**
 *
 *   그래서 두 가지를 고쳤다 — 상한을 올리고, **재조립을 없앴다.**
 */

/** 지역번호 없는 시내번호(02-123-4567). 이보다 짧으면 번호가 아니라 오타다. */
const MIN_DIGITS = 8;

/**
 * 국가번호를 붙인 국제 형식까지 담는 길이.
 *
 * 🔑 15는 임의로 고른 값이 아니다.
 *   ITU-T E.164가 국가번호를 포함한 전화번호의 최대 길이를 15자리로 정한다.
 *   그보다 긴 건 어느 나라에도 없으므로, 여기가 "번호가 아니다"라고 말할 수 있는 경계다.
 */
const MAX_DIGITS = 15;

/** 숫자만 남긴다. 길이 검사에만 쓰고, 저장에는 쓰지 않는다. */
export function phoneDigits(raw: string): string {
  return raw.replace(/\D/g, "");
}

export function isValidPhone(raw: string): boolean {
  const n = phoneDigits(raw).length;
  return n >= MIN_DIGITS && n <= MAX_DIGITS;
}

/**
 * 저장할 형태로 다듬는다.
 *
 * 🔑 이제 **아무것도 재조립하지 않는다.**
 *   전에는 자릿수를 보고 한국 휴대폰 규칙으로 하이픈을 끼워 넣었는데,
 *   그러면 `0503-1234-5678`이나 해외 번호가 **사용자가 넣지 않은 모양**이 된다.
 *   연락이 닿는 것이 목적인 값을 바꿔서 저장할 이유가 없다.
 *
 *   대신 앞뒤 공백과 연속 공백만 정리한다. 사람이 친 그대로가 사람이 읽기에도 가장 낫다 —
 *   `010-1234-5678`이든 `+82 10 1234 5678`이든 넣은 사람이 그렇게 부르는 번호다.
 */
export function normalizePhone(raw: string): string {
  return raw.trim().replace(/\s+/g, " ");
}
